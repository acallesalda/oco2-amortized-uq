#!/usr/bin/env python3
"""make_bo_dag.py
Write the one DAG that searches, retrains and scores all six models.

    python3 chtc/make_bo_dag.py
    mkdir -p chtc/logs
    cd chtc/bo && condor_submit_dag bo_all.dag

That is the whole pipeline. For each of the six studies it runs 25 Bayesian-optimization
trials, picks the winner out of the trial records, retrains it at twice the trial epoch
count, and then -- once both the deterministic and the flow model of a task exist -- scores
them together on the held-out test partition:

    propose_r0 -> trials_r0 (5 GPUs) -> propose_r1 -> ... -> trials_r4
                                                                |
                                                             select  (1 min, CPU)
                                                                |
                                                              final  (1 GPU, 2x epochs)
                                                                |
    det_<task>_final + nf_<task>_final ------------------->  eval_<task>  (1 GPU, test set)

Six studies x (5 propose + 5 trial waves + select + final) + 4 scoring jobs = 76 nodes,
150 search trials, 6 retrained models, 4 test-set artifacts, one submit.

Why generated rather than hand-written
--------------------------------------
The search is adaptive but the submit files must be static: HTCondor decides what to
transfer at submit time, and /staging cannot be globbed then. What saves it is that the
*names* are deterministic even though the contents are not -- round k's propose job needs
exactly the records `bo_<study>_r<r>_t<t>.json` for r < k -- so the file lists can be
written in advance and only their contents change as the search runs.

Ten files come out, not seventy: everything that varies between two nodes of the same
kind is a DAG VARS macro (`$(study)`, `$(rnd)`), and everything that is a constant of the
whole run (the covariate preset, the epoch counts, the staging namespace) is substituted
in here, at generation time, where it is visible in the file rather than buried in a
command line somebody has to remember to repeat.

What is NOT searched, and why
-----------------------------
  covariates   the scientific comparison, settled by covariates.dag before this runs.
               Tuning over it would make that ablation incoherent.
  epochs       trials rank configurations, they do not produce models. The winner is
               retrained at 2x by bo_final.sh.
  the warm start for the flows -- it is forced OFF. See chtc/bo_studies.sh.
"""

from __future__ import annotations

import argparse
from pathlib import Path

HERE = Path(__file__).resolve().parent

STUDIES = ("det_xco2", "det_profiles", "det_last4",
           "nf_xco2", "nf_profiles", "nf_last4")

# task -> (deterministic study, flow study). `last4_marginal` is the published Table 3's
# second block: the 20-level models scored on levels 17-20, which is a slice of the profile
# models' predictive and not a separate pair of checkpoints.
TASKS = (
    ("xco2", "det_xco2", "nf_xco2"),
    ("profiles", "det_profiles", "nf_profiles"),
    ("last4", "det_last4", "nf_last4"),
    ("last4_marginal", "det_profiles", "nf_profiles"),
)

HEADER = """\
# GENERATED by chtc/make_bo_dag.py -- regenerate rather than edit.
#   {cmd}
"""

# ---------------------------------------------------------------------------------
# propose_r<k>.sub -- one per round, shared by all six studies.
#
# The only thing that differs between rounds is the list of earlier records the job has to
# be given, which is why these are per-round rather than one file: round 0 reads nothing,
# round 4 reads twenty. The study is a VARS macro, so six studies share five files.
# ---------------------------------------------------------------------------------
PROPOSE_SUB = """\
{header}#
# Propose round {rnd} of a study's Bayesian optimization. CPU only, under a minute.
#
# Reads the {n_history} record(s) the earlier rounds left on /staging and writes the next
# {batch} parameter files. Round 0 reads nothing and proposes the published configuration
# as its trial 0, so every study contains its own baseline.{extra_baseline_note}

include : ../site.conf

universe             = container
container_image      = $(SIF)
container_target_dir = /workspace/project

executable = ../bo_round.sh
arguments  = $(study) {rnd} {batch}

transfer_input_files = ../job_common.sh, \\
                       ../oco2_code.tar.gz{history}{extra_baseline}

should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
transfer_output_files   = {params_out}
transfer_output_remaps  = "{params_remap}"

requirements = $(STAGING_REQ)

request_cpus   = 1
request_memory = 4GB

# 20 GB for a job that reads a handful of 800-byte JSON files and writes five more.
#
# It is not the propose step that needs it: oco2_setup untars the whole code tarball, and
# that tarball grows every time fetch_results.sh unpacks results back into the checkout.
# At 4 GB a round-1 node was held with "disk usage exceeded request_disk". The real fix is
# keeping the tarball small (make_code_tarball.sh warns above 50 MB and names the biggest
# members), but a one-minute CPU job is the wrong place to be tight: the request is free,
# and a held propose node stalls a whole study.
request_disk   = 20GB

stream_output = true
stream_error  = true

log    = ../logs/bo_$(study)_propose_r{rnd}.log
output = ../logs/bo_$(study)_propose_r{rnd}.out
error  = ../logs/bo_$(study)_propose_r{rnd}.err

max_retries = 0
queue
"""

# ---------------------------------------------------------------------------------
# trial.sub -- one file for all thirty waves.
# ---------------------------------------------------------------------------------
TRIAL_SUB = """\
{header}#
# One wave of {batch} trials: study $(study), round $(rnd), {epochs} epochs each.
#
# The hyperparameters are not on the command line. Each proc reads
# bo_$(study)_r$(rnd)_t$(trial).params.json, which the round's propose node wrote to
# /staging -- that is what lets a static submit file run an adaptive search.

include : ../site.conf
include : ../job_resources.conf
include : ../gpu_constraints.conf

universe             = container
container_image      = $(SIF)
container_target_dir = /workspace/project

executable = ../bo_trial.sh
arguments  = $(study) $(rnd) $(trial) {covariates} {epochs}
{split_env}
transfer_input_files = ../job_common.sh, \\
                       ../bo_studies.sh, \\
                       ../oco2_code.tar.gz, \\
                       $(OSDF)/oco2_processed_train.tar.gz, \\
                       $(OSDF)/oco2_processed_test.tar.gz, \\
                       $(OSDF)/oco2_profile_stats.tar.gz, \\
{split_archives}
                       $(OSDF)/results/{run}/bo_$(study)_r$(rnd)_t$(trial).params.json

should_transfer_files   = YES
when_to_transfer_output = ON_EXIT

# Two outputs: the record the next propose node reads, and an archive with the hydra logs
# and configs for when a trial has to be explained after the fact. bo_trial.sh deletes the
# .pt files before the archive is packed -- 150 checkpoints nobody will score is four GB
# of transfer for nothing, and the winner is retrained at full length anyway.
transfer_output_files  = bo_$(study)_r$(rnd)_t$(trial).json, \\
                         bo_$(study)_r$(rnd)_t$(trial).tar.gz
transfer_output_remaps  = "bo_$(study)_r$(rnd)_t$(trial).json = $(OSDF)/results/{run}/bo_$(study)_r$(rnd)_t$(trial).json ; \\
                           bo_$(study)_r$(rnd)_t$(trial).tar.gz = $(OSDF)/results/{run}/bo_$(study)_r$(rnd)_t$(trial).tar.gz"

request_gpus = 1
+WantGPULab  = true
+GPUJobLength = "short"
gpus_minimum_capability = $(GPU_MIN_CAP)
gpus_maximum_capability = $(GPU_MAX_CAP)
gpus_minimum_memory     = $(GPU_MIN_MEM)

requirements = $(STAGING_REQ)

request_cpus   = $(CPUS)
request_memory = $(MEM_GB)GB
request_disk   = $(DISK_GB)GB

stream_output = true
stream_error  = true

log    = ../logs/bo_$(study)_r$(rnd)_t$(trial){suffix}.log
output = ../logs/bo_$(study)_r$(rnd)_t$(trial){suffix}.out
error  = ../logs/bo_$(study)_r$(rnd)_t$(trial){suffix}.err

# A retry cannot succeed: ON_EXIT already uploaded the output objects and OSDF refuses to
# overwrite them, so the second attempt is held with a transfer error that says nothing
# about the first failure. Clean and resubmit instead.
max_retries = 0

queue trial in ({trials})
"""

# ---------------------------------------------------------------------------------
# select.sub -- one file, six nodes.
# ---------------------------------------------------------------------------------
SELECT_SUB = """\
{header}#
# Pick study $(study)'s winner out of its {n_trials} trial records. CPU only, under a minute.
#
# Every record is named explicitly: /staging cannot be globbed at submit time, but after
# {rounds} rounds of {batch} the names are known in advance. A trial that failed still
# wrote a record and still exited 0, so all {n_trials} are expected to be here; bo_select.py
# reports the failures and takes the minimum over the rest.

include : ../site.conf

universe             = container
container_image      = $(SIF)
container_target_dir = /workspace/project

executable = ../bo_select.sh
arguments  = $(study)

transfer_input_files = ../job_common.sh, \\
                       ../oco2_code.tar.gz{records}

should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
transfer_output_files   = bo_$(study)_best.json, \\
                          bo_$(study)_leaderboard.md
transfer_output_remaps  = "bo_$(study)_best.json = $(OSDF)/results/{run}/bo_$(study)_best.json ; \\
                           bo_$(study)_leaderboard.md = $(OSDF)/results/{run}/bo_$(study)_leaderboard.md"

requirements = $(STAGING_REQ)

request_cpus   = 1
request_memory = 4GB
request_disk   = 20GB

stream_output = true
stream_error  = true

log    = ../logs/bo_$(study)_select.log
output = ../logs/bo_$(study)_select.out
error  = ../logs/bo_$(study)_select.err

max_retries = 0
queue
"""

# ---------------------------------------------------------------------------------
# final.sub -- one file, six nodes.
# ---------------------------------------------------------------------------------
FINAL_SUB = """\
{header}#
# Retrain study $(study)'s winning configuration at {final_epochs} epochs -- twice what the
# trials ran at. The trials keep no checkpoint, so this is the first time the searched
# configuration exists as a model that can be scored.
#
# The configuration is read from bo_$(study)_best.json, which the select node wrote. It is
# not repeated on the command line: the model trained here and the configuration searched
# are then the same object by construction.

include : ../site.conf
include : ../job_resources.conf
include : ../gpu_constraints.conf

universe             = container
container_image      = $(SIF)
container_target_dir = /workspace/project

executable = ../bo_final.sh
arguments  = $(study) {covariates} {final_epochs}
{split_env}
transfer_input_files = ../job_common.sh, \\
                       ../bo_studies.sh, \\
                       ../oco2_code.tar.gz, \\
                       $(OSDF)/oco2_processed_train.tar.gz, \\
                       $(OSDF)/oco2_processed_test.tar.gz, \\
                       $(OSDF)/oco2_profile_stats.tar.gz, \\
{split_archives}
                       $(OSDF)/results/{run}/bo_$(study)_best.json

should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
transfer_output_files   = $(study)_final{suffix}.tar.gz
transfer_output_remaps  = "$(study)_final{suffix}.tar.gz = $(OSDF)/results/$(study)_final{suffix}.tar.gz"

request_gpus = 1
+WantGPULab  = true
# "medium" rather than "short": twice the trial epochs, and the search is free to pick a
# 512-wide backbone with twelve coupling layers.
+GPUJobLength = "medium"
gpus_minimum_capability = $(GPU_MIN_CAP)
gpus_maximum_capability = $(GPU_MAX_CAP)
gpus_minimum_memory     = $(GPU_MIN_MEM)

requirements = $(STAGING_REQ)

request_cpus   = $(CPUS)
request_memory = $(MEM_GB)GB
request_disk   = $(DISK_GB)GB

stream_output = true
stream_error  = true

log    = ../logs/$(study)_final{suffix}.log
output = ../logs/$(study)_final{suffix}.out
error  = ../logs/$(study)_final{suffix}.err

# max_retries = 0, deliberately: ON_EXIT uploads the archive even on failure and OSDF
# refuses to overwrite it, so a retry is held with a transfer error that says nothing
# about the real one. Clean and resubmit:
#   ./fetch_results.sh --clean $(study)_final
max_retries = 0
queue
"""

# ---------------------------------------------------------------------------------
# eval.sub -- one file, four nodes. The only jobs that read the test partition.
# ---------------------------------------------------------------------------------
EVAL_SUB = """\
{header}#
# Score task $(task) on the HELD-OUT TEST PARTITION, from the two retrained winners.
#
# The search ranked configurations on validation and the retrain picked its checkpoint on
# validation; neither ever saw these soundings. That is what makes this number reportable.

include : ../site.conf
include : ../job_resources.conf
include : ../gpu_constraints.conf

universe             = container
container_image      = $(SIF)
container_target_dir = /workspace/project

executable = ../bo_eval.sh
arguments  = $(task) {covariates} {tag}
{split_env}
transfer_input_files = ../job_common.sh, \\
                       ../bo_studies.sh, \\
                       ../oco2_code.tar.gz, \\
                       $(OSDF)/oco2_processed_train.tar.gz, \\
                       $(OSDF)/oco2_processed_test.tar.gz, \\
                       $(OSDF)/oco2_profile_stats.tar.gz, \\
{split_archives}
                       $(OSDF)/results/$(det_study)_final{suffix}.tar.gz, \\
                       $(OSDF)/results/$(flow_study)_final{suffix}.tar.gz

should_transfer_files   = YES
when_to_transfer_output = ON_EXIT
transfer_output_files   = eval_$(task)_{tag}.tar.gz
transfer_output_remaps  = "eval_$(task)_{tag}.tar.gz = $(OSDF)/results/eval_$(task)_{tag}.tar.gz"

# A Laplace refit over a few thousand training soundings, then the test pass and 512 flow
# samples per sounding. Tens of minutes, so "short" -- and short jobs match more slots,
# which matters when this is the last thing between the run and the tables.
request_gpus = 1
+WantGPULab  = true
+GPUJobLength = "short"
gpus_minimum_capability = $(GPU_MIN_CAP)
gpus_maximum_capability = $(GPU_MAX_CAP)
gpus_minimum_memory     = $(GPU_MIN_MEM)

requirements = $(STAGING_REQ)

request_cpus   = $(CPUS)
request_memory = $(MEM_GB)GB
request_disk   = $(DISK_GB)GB

stream_output = true
stream_error  = true

log    = ../logs/eval_$(task)_{tag}.log
output = ../logs/eval_$(task)_{tag}.out
error  = ../logs/eval_$(task)_{tag}.err

# max_retries = 0, deliberately -- see final.sub.
#   ./fetch_results.sh --clean eval_$(task)_{tag}
max_retries = 0
queue
"""


def write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8")
    print("wrote {}".format(path))


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--study", action="append", choices=list(STUDIES),
                    help="may be given more than once; default is all six")
    ap.add_argument("--rounds", type=int, default=5)
    ap.add_argument("--batch", type=int, default=5,
                    help="trials per round, evaluated concurrently. rounds x batch is the "
                         "trial count per study")
    ap.add_argument("--covariates", default="scene_prior",
                    help="the preset every study is searched under, held fixed")
    ap.add_argument("--epochs", type=int, default=20,
                    help="epochs per search trial")
    ap.add_argument("--final-multiplier", type=int, default=2,
                    help="the winner is retrained at this many times --epochs")
    ap.add_argument("--tag", default="bo", help="names the scoring artifacts")
    ap.add_argument("--split", default="group_split_v1",
                    choices=["group_split_v1", "replicate_split_v1"],
                    help="which partition every node of this graph trains and scores on. "
                         "It selects the experiment-config family (bo_studies.sh), the "
                         "weights tree, the statistics and the scoring artifact directory "
                         "-- all through OCO2_SPLIT in each job's environment.")
    ap.add_argument("--baseline-run", default=None,
                    help="staging namespace of an earlier run whose per-study winners "
                         "(bo_<study>_best.json) are enqueued as a second baseline in "
                         "round 0. Defaults to `bo25` -- the group split's search -- when "
                         "--split is not the group split, and to nothing otherwise. Pass "
                         "`none` to disable. It costs one trial in twenty-five and puts "
                         "one identical configuration in both searches, which is the only "
                         "way the pair contains a same-model comparison across splits as "
                         "well as a same-protocol one.")
    ap.add_argument("--out-dir", default=None,
                    help="where to write the generated files. Default: chtc/bo for the "
                         "group split, chtc/bo_replicate otherwise, so that generating "
                         "one graph cannot overwrite the other's submit files or its "
                         "leaderboards.")
    ap.add_argument("--run", default="bo25",
                    help="subdirectory of /staging/.../oco2/results for this run's trial "
                         "records. A fresh name is what keeps a re-run from colliding "
                         "with the records of an earlier one -- OSDF refuses to overwrite "
                         "an object, so a collision is a held job, not a warning")
    ap.add_argument("--max-waves", type=int, default=3,
                    help="trial waves running at once, across all studies. One wave is "
                         "%(default)s x --batch GPU jobs")
    ap.add_argument("--max-solo", type=int, default=6,
                    help="retrain and scoring jobs running at once")
    args = ap.parse_args()

    studies = args.study or list(STUDIES)
    rounds, batch = args.rounds, args.batch
    n_trials = rounds * batch
    final_epochs = args.epochs * args.final_multiplier
    # Two graphs, two directories. The generated .sub files reach the shared scripts as
    # ../bo_trial.sh and the config as ../site.conf, so any sibling of chtc/bo works.
    if args.out_dir:
        out = Path(args.out_dir)
    else:
        out = HERE / ("bo" if args.split == "group_split_v1" else "bo_replicate")
    out.mkdir(exist_ok=True, parents=True)

    # Everything a second run writes to /staging must be named differently from the first
    # run's, or OSDF refuses the upload and the job is held with a transfer error that
    # says nothing about the cause. `--run` namespaces the trial records, the archive
    # suffix namespaces the retrained winners, and `--tag` namespaces the artifacts; the
    # first two follow --split automatically and the third cannot, because it also names
    # the .npz inside the archive.
    if args.split != "group_split_v1" and args.tag == "bo":
        raise SystemExit(
            "--split {} needs its own --tag (e.g. --tag borep): with --tag bo the "
            "scoring archives would be named eval_<task>_bo.tar.gz, which is what the "
            "group-split run already put in /staging.".format(args.split))
    if args.split != "group_split_v1" and args.run == "bo25":
        raise SystemExit(
            "--split {} needs its own --run (e.g. --run bo25rep): with --run bo25 the "
            "trial records would collide with the group-split search's.".format(args.split))

    suffix = "" if args.split == "group_split_v1" else "_rep"
    split_archives = ("                       $(OSDF)/oco2_split_v1.tar.gz, \\\n"
                      "                       $(OSDF)/oco2_covariates_v1.tar.gz, \\")
    if args.split == "replicate_split_v1":
        # One archive, not two: the replicate split's augmented table travels with its
        # split table, because extract_covariates.py is split-independent and has already
        # run once.
        split_archives = "                       $(OSDF)/oco2_replicate_split_v1.tar.gz, \\"
    split_env = 'environment = "OCO2_SPLIT={}"\n'.format(args.split)

    # The other run's winners, transferred into round 0 only. bo_round.sh looks for the
    # file by name and passes --extra-baseline when it is there, so a graph generated
    # without this simply does not get the extra trial.
    baseline_run = args.baseline_run
    if baseline_run is None:
        baseline_run = "" if args.split == "group_split_v1" else "bo25"
    if baseline_run == "none":
        baseline_run = ""
    extra_baseline = ""
    extra_baseline_note = ""
    if baseline_run:
        extra_baseline = (", \\\n                       "
                          "$(OSDF)/results/{}/bo_$(study)_best.json".format(baseline_run))
        extra_baseline_note = (
            "\n#\n# Round 0 also enqueues the winner of the earlier `{}` run as a second"
            " baseline,\n# so this search contains one configuration that was also trained"
            " on the other split.\n# bo_round.sh passes it only if the file actually"
            " transferred; a missing one costs\n# the extra trial and nothing else."
            .format(baseline_run))

    cmd = ("python3 chtc/make_bo_dag.py --rounds {} --batch {} --covariates {} "
           "--epochs {} --final-multiplier {} --run {} --tag {} --split {}{}".format(
               rounds, batch, args.covariates, args.epochs, args.final_multiplier,
               args.run, args.tag, args.split,
               "" if args.baseline_run is None
               else " --baseline-run {}".format(args.baseline_run)))
    header = HEADER.format(cmd=cmd)
    fmt = dict(header=header, batch=batch, covariates=args.covariates,
               epochs=args.epochs, final_epochs=final_epochs, run=args.run,
               tag=args.tag, rounds=rounds, n_trials=n_trials,
               split=args.split, split_archives=split_archives, split_env=split_env,
               suffix=suffix, baseline_run=baseline_run)

    # ---- the round-by-round propose files ------------------------------------------
    for rnd in range(rounds):
        history = "".join(
            ", \\\n                       "
            "$(OSDF)/results/{}/bo_$(study)_r{}_t{}.json".format(args.run, r, t)
            for r in range(rnd) for t in range(batch))
        params_out = ", \\\n                          ".join(
            "bo_$(study)_r{}_t{}.params.json".format(rnd, t) for t in range(batch))
        params_remap = " ; \\\n                           ".join(
            "bo_$(study)_r{rnd}_t{t}.params.json = "
            "$(OSDF)/results/{run}/bo_$(study)_r{rnd}_t{t}.params.json".format(
                rnd=rnd, t=t, run=args.run) for t in range(batch))
        write(out / "propose_r{}.sub".format(rnd),
              PROPOSE_SUB.format(rnd=rnd, n_history=rnd * batch, history=history,
                                 extra_baseline=extra_baseline if rnd == 0 else "",
                                 extra_baseline_note=(extra_baseline_note
                                                      if rnd == 0 else ""),
                                 params_out=params_out, params_remap=params_remap,
                                 **fmt))

    # ---- the four files that serve every node of their kind ------------------------
    write(out / "trial.sub",
          TRIAL_SUB.format(trials=" ".join(str(t) for t in range(batch)), **fmt))
    records = "".join(
        ", \\\n                       "
        "$(OSDF)/results/{}/bo_$(study)_r{}_t{}.json".format(args.run, r, t)
        for r in range(rounds) for t in range(batch))
    write(out / "select.sub", SELECT_SUB.format(records=records, **fmt))
    write(out / "final.sub", FINAL_SUB.format(**fmt))
    write(out / "eval.sub", EVAL_SUB.format(**fmt))

    # ---- the DAG -------------------------------------------------------------------
    dag = [
        header.rstrip("\n"),
        "#",
        "#     mkdir -p chtc/logs && cd chtc/bo && condor_submit_dag bo_all.dag",
        "#",
        "# {} studies x {} rounds x {} trials = {} search trials, then {} retrains at {} "
        "epochs,".format(len(studies), rounds, batch, len(studies) * n_trials,
                         len(studies), final_epochs),
        "# then {} scoring jobs on the test partition.".format(len(TASKS)),
        "#",
        "# Covariate set: {}, fixed for every study. Trial epochs: {}. Final epochs: {}."
        .format(args.covariates, args.epochs, final_epochs),
        "#",
        "# Prerequisites, all in /staging (./fetch_results.sh --status will say):",
        "#   oco2_processed_{train,test}.tar.gz, oco2_profile_stats.tar.gz  stage_data.sh",
        "#   oco2_split_v1.tar.gz                                           prep.sub",
        "#   oco2_covariates_v1.tar.gz                                      covariates.sub",
        "#",
        "# This run's trial records go to results/{}/ rather than results/bo/, so nothing".format(args.run),
        "# here can collide with an earlier search. OSDF refuses to overwrite an object:",
        "# a collision is a held job, not a warning. Make the directory before submitting --",
        "# if it is absent the first five uploads are held and the graph stalls at round 0:",
        "#",
        '#   NETID=$(whoami); mkdir -p "/staging/${{NETID:0:1}}/${{NETID}}/oco2/results/{}"'.format(args.run),
        "",
    ]

    for study in studies:
        dag.append("# " + "-" * 74)
        dag.append("# {}".format(study))
        for rnd in range(rounds):
            dag.append('JOB {s}_propose_r{r} propose_r{r}.sub'.format(s=study, r=rnd))
            dag.append('VARS {s}_propose_r{r} study="{s}"'.format(s=study, r=rnd))
            dag.append('JOB {s}_trials_r{r}  trial.sub'.format(s=study, r=rnd))
            dag.append('VARS {s}_trials_r{r} study="{s}" rnd="{r}"'.format(s=study, r=rnd))
            dag.append('PARENT {s}_propose_r{r} CHILD {s}_trials_r{r}'.format(s=study, r=rnd))
            if rnd:
                dag.append('PARENT {s}_trials_r{p} CHILD {s}_propose_r{r}'.format(
                    s=study, p=rnd - 1, r=rnd))
        dag.append('JOB {s}_select select.sub'.format(s=study))
        dag.append('VARS {s}_select study="{s}"'.format(s=study))
        dag.append('PARENT {s}_trials_r{r} CHILD {s}_select'.format(s=study, r=rounds - 1))
        dag.append('JOB {s}_final final.sub'.format(s=study))
        dag.append('VARS {s}_final study="{s}"'.format(s=study))
        dag.append('PARENT {s}_select CHILD {s}_final'.format(s=study))
        dag.append("")

    dag.append("# " + "-" * 74)
    dag.append("# The test partition. Each job needs both models of its task, which is why")
    dag.append("# these are the only nodes with two parents.")
    for task, det, flow in TASKS:
        if det not in studies or flow not in studies:
            dag.append("# eval_{}: skipped, {} or {} is not in this run".format(
                task, det, flow))
            continue
        dag.append('JOB eval_{t} eval.sub'.format(t=task))
        dag.append('VARS eval_{t} task="{t}" det_study="{d}" flow_study="{f}"'.format(
            t=task, d=det, f=flow))
        dag.append('PARENT {d}_final {f}_final CHILD eval_{t}'.format(
            d=det, f=flow, t=task))
    dag.append("")

    # ---- throttles ------------------------------------------------------------------
    dag += [
        "# " + "-" * 74,
        "# Throttles. DAGMan counts a node, not a proc: one trial wave is ONE job here and",
        "# {} GPUs on the pool, so --max-waves {} is up to {} concurrent trial jobs. The".format(
            batch, args.max_waves, args.max_waves * batch),
        "# retrains and the scoring jobs are one GPU each and are counted separately;",
        "# they only start once a study's five waves are finished, so the two limits do",
        "# not stack in practice.",
        "MAXJOBS WAVE {}".format(args.max_waves),
        "MAXJOBS SOLO {}".format(args.max_solo),
        "",
    ]
    for study in studies:
        for rnd in range(rounds):
            dag.append("CATEGORY {s}_trials_r{r} WAVE".format(s=study, r=rnd))
    for study in studies:
        dag.append("CATEGORY {s}_final SOLO".format(s=study))
    for task, det, flow in TASKS:
        if det in studies and flow in studies:
            dag.append("CATEGORY eval_{t} SOLO".format(t=task))
    dag += [
        "",
        "# One line per node, rewritten every 30 seconds:  watch cat chtc/bo/bo_all.status",
        "NODE_STATUS_FILE bo_all.status 30",
        "",
    ]

    write(out / "bo_all.dag", "\n".join(dag))
    print()
    print("{} studies x {} trials = {} GPU trials, {} retrains at {} epochs, {} test-set "
          "scoring jobs".format(len(studies), n_trials, len(studies) * n_trials,
                                len(studies), final_epochs, len(TASKS)))
    print("covariates={}  trial epochs={}  staging namespace=results/{}".format(
        args.covariates, args.epochs, args.run))
    return 0


